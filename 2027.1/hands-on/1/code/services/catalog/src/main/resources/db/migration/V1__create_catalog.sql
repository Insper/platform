-- Flyway runs this once, inside the schema "catalog" (spring.flyway.schemas).
CREATE TABLE catalog.venues (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(200) NOT NULL,
    city      VARCHAR(100) NOT NULL,
    capacity  INTEGER      NOT NULL CHECK (capacity > 0)
);

CREATE TABLE catalog.events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200)  NOT NULL,
    category    VARCHAR(20)   NOT NULL CHECK (category IN ('CONCERT', 'SPORTS', 'FESTIVAL', 'THEATER')),
    venue_id    BIGINT        NOT NULL REFERENCES catalog.venues (id),
    starts_at   TIMESTAMPTZ   NOT NULL,
    price_from  NUMERIC(10,2) NOT NULL CHECK (price_from >= 0)
);
-- No secondary indexes on purpose: lab 6 measures the listing query before and after adding them.
