"""Retrieval evaluation: does the vector search find the right events? (hit@k and MRR)

The catalog seed of lab 1 is generated by a formula, so the right answers are known exactly:
event g is title ["Concert", "Match", "Festival", "Play"][g % 4] + " #g", at venue 1 + (g * 7) % 50.

    uv run scripts/eval_retrieval.py --k 5 --limit 300
"""
import argparse

import httpx

CITIES = ["São Paulo", "Rio de Janeiro", "Belo Horizonte", "Porto Alegre", "Curitiba",
          "Salvador", "Recife", "Fortaleza", "Brasília", "Manaus"]
KINDS = ["Stadium", "Arena", "Hall", "Theater", "Club"]
TITLES = ["Concert", "Match", "Festival", "Play"]
WORDS = {"Concert": "concert", "Match": "match", "Festival": "festival", "Play": "play"}


def event(g: int) -> dict:
    if g == 1:
        return {"id": 1, "kind": "Festival", "venue_kind": "Stadium", "city": "São Paulo"}
    v = 1 + (g * 7) % 50
    return {"id": g, "kind": TITLES[g % 4], "venue_kind": KINDS[(v - 1) % 5], "city": CITIES[(v - 1) // 5]}


def labeled(limit: int) -> list[tuple[str, set[str]]]:
    events = [event(g) for g in range(1, limit + 1)]
    cases = []
    for g in [7, 42, 118, 199, 256]:  # exact lookups: one right answer
        if g <= limit:
            e = event(g)
            cases.append((f"When is {e['kind']} #{g}?", {f"event:{g}"}))
    for kind, city in [("Festival", "Recife"), ("Play", "Curitiba"), ("Match", "Salvador"),
                       ("Concert", "Manaus"), ("Festival", "São Paulo")]:  # open questions: many right answers
        right = {f"event:{e['id']}" for e in events if e["kind"] == kind and e["city"] == city}
        if right:
            cases.append((f"Is there any {WORDS[kind]} in {city}?", right))
    cases.append(("the big festival night at the stadium in São Paulo", {"event:1"}))
    return cases


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://localhost:8088")
    ap.add_argument("--k", type=int, default=5)
    ap.add_argument("--limit", type=int, default=300, help="how many events were ingested")
    args = ap.parse_args()
    hits, rr = 0, 0.0
    print("| question | relevant | first relevant rank |\n|---|---|---|")
    for question, right in labeled(args.limit):
        found = httpx.post(f"{args.url}/assistant/search", json={"query": question, "k": args.k}, timeout=60).json()
        ranks = [i + 1 for i, h in enumerate(found) if h["id"] in right]
        rank = ranks[0] if ranks else None
        hits += rank is not None
        rr += 1 / rank if rank else 0
        print(f"| {question} | {len(right)} | {rank or '-'} |")
    n = len(labeled(args.limit))
    print(f"\nhit@{args.k} = {hits / n:.2f}   MRR = {rr / n:.2f}   ({n} questions)")


if __name__ == "__main__":
    main()
