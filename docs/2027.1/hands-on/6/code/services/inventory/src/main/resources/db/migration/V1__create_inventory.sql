-- Seats of every event, and the holds that reserve them for a few minutes.
-- event_id refers to catalog.events, but there is NO foreign key across services.
CREATE TABLE inventory.seats (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT        NOT NULL,
    section      VARCHAR(10)   NOT NULL,
    seat_row     INTEGER       NOT NULL,
    seat_number  INTEGER       NOT NULL,
    price        NUMERIC(10,2) NOT NULL,
    status       VARCHAR(10)   NOT NULL DEFAULT 'AVAILABLE'
                 CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD')),
    hold_id      UUID,
    version      INTEGER       NOT NULL DEFAULT 0,          -- optimistic locking
    UNIQUE (event_id, section, seat_row, seat_number)       -- also the index for "seats of an event"
);

CREATE TABLE inventory.holds (
    id          UUID         PRIMARY KEY,
    event_id    BIGINT       NOT NULL,
    user_id     VARCHAR(64)  NOT NULL,
    status      VARCHAR(10)  NOT NULL CHECK (status IN ('ACTIVE', 'CONFIRMED', 'RELEASED', 'EXPIRED')),
    expires_at  TIMESTAMPTZ  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- which seats each hold asked for: lets us AUDIT double bookings afterwards
CREATE TABLE inventory.hold_seats (
    hold_id  UUID   NOT NULL REFERENCES inventory.holds (id),
    seat_id  BIGINT NOT NULL REFERENCES inventory.seats (id),
    PRIMARY KEY (hold_id, seat_id)
);
